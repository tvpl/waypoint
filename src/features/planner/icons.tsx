export const ICON_NAMES = Object.keys(PLAN_ICONS);

export function PlanIcon({ name, fallback = "box", className, size = 16, strokeWidth = 1.75 }: { name?: string | null; fallback?: string; className?: string; size?: number; strokeWidth?: number }) {
  const Icon = (name && PLAN_ICONS[name]?.icon) || PLAN_ICONS[fallback]?.icon || Box;
  return <Icon className={className} size={size} strokeWidth={strokeWidth} aria-hidden />;
}

